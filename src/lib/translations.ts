export function translateTicketSubject(subject: string, language: Language): string {
  if (!subject) return subject;
  const prefix = /^\[Self-Resolved\]\s*/i;
  if (!prefix.test(subject)) return subject;
  const translatedPrefix = language === 'en' ? '[Auto-Resolved] ' : '[Diselesaikan Sistem] ';
  return subject.replace(prefix, translatedPrefix);
}
